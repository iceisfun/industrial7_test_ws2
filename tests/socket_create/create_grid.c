static void run_group(int af, int ty) {
    unsigned i;
    int seen = 0;
    SC_UP();
    for (i = 0; i < sizeof grid / sizeof *grid; i++) {
        const struct grow *r = &grid[i];
        SOCKET s;
        if (r->af != af || r->ty != ty) continue;
        seen++;
        sc_seterr(0xdeadbeef);
        s = sc_make(af, ty, r->pr, WSA_FLAG_OVERLAPPED);
        if (r->err) {
            t_check(s == INVALID_SOCKET, __FILE__, __LINE__, "fails", "af=%d ty=%d pr=%d", af, ty, r->pr);
            t_check(sc_err() == r->err, __FILE__, __LINE__, "error", "af=%d ty=%d pr=%d got %d want %d", af, ty, r->pr, sc_err(), r->err);
        } else if (s == INVALID_SOCKET) {
            if (r->rty == SOCK_RAW && sc_err() == WSAEACCES) continue;
            t_check(0, __FILE__, __LINE__, "succeeds", "af=%d ty=%d pr=%d error %d", af, ty, r->pr, sc_err());
        } else {
            WSAPROTOCOL_INFOW pi;
            t_check(sc_getinfo(s, &pi) == 0, __FILE__, __LINE__, "info", NULL);
            t_check(pi.iAddressFamily == r->raf && pi.iSocketType == r->rty && pi.iProtocol == r->rpr, __FILE__, __LINE__, "resolved triple",
                    "af=%d ty=%d pr=%d got %d/%d/%d want %d/%d/%d", af, ty, r->pr, pi.iAddressFamily, pi.iSocketType, pi.iProtocol, r->raf, r->rty, r->rpr);
        }
        sc_close(s);
    }
    CHECK(seen > 0);
}

