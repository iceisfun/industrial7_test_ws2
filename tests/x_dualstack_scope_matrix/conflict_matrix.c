static void run_conf(const struct crow *t, int n, int ty, int ex) {
    if (!s_up()) return;
    for (int i = 0; i < n; i++) {
        char a[32]; SOCKET s1 = s_mk(t[i].sk1, ty), s2 = s_mk(t[i].sk2, ty); int r1, r2, e = 0; unsigned short p;
        if (ex == 1) { s_setint(s1, SOL_SOCKET, SO_REUSEADDR, 1); s_setint(s2, SOL_SOCKET, SO_REUSEADDR, 1); }
        if (ex == 2) s_setint(s1, SOL_SOCKET, SO_EXCLUSIVEADDRUSE, 1);
        r1 = U(bind)(s1, (struct sockaddr *)a, s_mkaddr(a, t[i].ak1, 0));
        CHECK(r1 == 0);
        p = s_port(s1);
        r2 = U(bind)(s2, (struct sockaddr *)a, s_mkaddr(a, t[i].ak2, p));
        if (r2) e = s_err();
        CHECKF(e == t[i].err, "%s/%s then %s/%s got err %d want %d", SK_NAME[t[i].sk1], AK_NAME[t[i].ak1], SK_NAME[t[i].sk2], AK_NAME[t[i].ak2], e, t[i].err);
        s_close(s1); s_close(s2);
    }
}
#define NX(t) ((int)(sizeof(t) / sizeof((t)[0])))
TEST(dsm_conflict_tcp_default)   { run_conf(X_tcp_0, NX(X_tcp_0), SOCK_STREAM, 0); }
TEST(dsm_conflict_tcp_reuseaddr) { run_conf(X_tcp_1, NX(X_tcp_1), SOCK_STREAM, 1); }
TEST(dsm_conflict_tcp_exclusive) { run_conf(X_tcp_2, NX(X_tcp_2), SOCK_STREAM, 2); }
